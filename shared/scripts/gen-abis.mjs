// Generates src/abis.generated.ts from Foundry build output (contracts/out).
// Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = join(root, "contracts", "out");
const contracts = [
  "DrippVaultFactory",
  "DrippVault",
  "PTToken",
  "YTToken",
  "DividendOracle",
  "DrippRouter",
  "IScaledUIAmount",
];

let ts = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\n\n";
for (const name of contracts) {
  const file = name === "IScaledUIAmount" ? "IScaledUIAmount.sol" : `${name}.sol`;
  const { abi } = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  ts += `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(root, "shared", "src", "abis.generated.ts"), ts);
console.log(`wrote ${contracts.length} ABIs`);
